function renderByLanguage(lang) {
  const t = translations[lang];
  if (!t) return;

  mainTitle.innerText = t.mainTitle;
  subTitle.innerText = t.subTitle;
  catAptechka.innerText = t.catAptechka;
  catByt.innerText = t.catByt;
  catOdezhda.innerText = t.catOdezhda;
  footerText.innerText = t.footer;
  aptechkaCount.innerText = t.aptechkaCount;
  bytCount.innerText = t.bytCount;
  odezhdaCount.innerText = t.odezhdaCount;

  function buildGrid(itemsArray, containerId) {
    const container = document.getElementById(containerId);
    if (!container) return;
    container.innerHTML = '';
    itemsArray.forEach((item, idx) => {
      const translatedName = t.items[item.name] || item.name;
      const card = document.createElement('div');
      card.className = 'item-card';
      const emojiDiv = document.createElement('div');
      emojiDiv.className = 'item-emoji';
      emojiDiv.textContent = item.emoji || '📦';
      const nameSpan = document.createElement('div');
      nameSpan.className = 'item-name';
      nameSpan.textContent = translatedName;
      const numberSpan = document.createElement('div');
      numberSpan.className = 'item-number';
      numberSpan.textContent = `${idx + 1}`;
      card.appendChild(emojiDiv);
      card.appendChild(nameSpan);
      card.appendChild(numberSpan);
      container.appendChild(card);
    });
  }

  buildGrid(aptechkaRaw, 'aptechka-grid');
  buildGrid(bytRaw, 'byt-grid');
  buildGrid(odezhdaRaw, 'odezhda-grid');
}

function getBrowserLang() {
  const navLang = navigator.language || navigator.userLanguage;
  if (navLang.startsWith('ru')) return 'ru';
  if (navLang.startsWith('en')) return 'en';
  if (navLang.startsWith('de')) return 'de';
  if (navLang.startsWith('es')) return 'es';
  if (navLang.startsWith('fr')) return 'fr';
  return 'ru';
}

let currentLang = getBrowserLang();
renderByLanguage(currentLang);

// активация кнопок
const btns = langControls.querySelectorAll('button');
btns.forEach(btn => {
  btn.classList.remove('active');
  if (btn.getAttribute('data-lang') === currentLang) btn.classList.add('active');
  btn.addEventListener('click', (e) => {
    const lang = btn.getAttribute('data-lang');
    currentLang = lang;
    renderByLanguage(lang);
    btns.forEach(b => b.classList.remove('active'));
    btn.classList.add('active');
  });
});